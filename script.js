const root = document.documentElement;
const toggle = document.querySelector("[data-lang-toggle]");
let activeLang = localStorage.getItem("qimam-lang") || "en";

function applyLanguage(lang) {
  activeLang = lang;
  root.lang = lang;
  root.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.setAttribute("dir", root.dir);
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (translations[lang][key]) node.textContent = translations[lang][key];
  });
  if (toggle) toggle.textContent = lang === "ar" ? "EN" : "AR";
  localStorage.setItem("qimam-lang", lang);
}

toggle?.addEventListener("click", () => {
  applyLanguage(activeLang === "ar" ? "en" : "ar");
});

applyLanguage(activeLang);

const revealItems = document.querySelectorAll("[data-reveal]");

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12 }
  );

  revealItems.forEach((item) => observer.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
}

document.querySelectorAll("[data-carousel]").forEach((carousel) => {
  const viewport = carousel.querySelector(".carousel-viewport");
  const slides = [...carousel.querySelectorAll("[data-slide]")];
  const dots = [...carousel.querySelectorAll("[data-carousel-dot]")];
  const prev = carousel.querySelector("[data-carousel-prev]");
  const next = carousel.querySelector("[data-carousel-next]");
  const spotlight = document.createElement("div");
  spotlight.className = "preview-spotlight";
  spotlight.innerHTML = `
    <div class="preview-spotlight__bar">
      <span data-preview-title>Project preview</span>
      <button type="button" class="preview-close" data-preview-close aria-label="Close preview">x</button>
    </div>
    <iframe title="Expanded project preview" loading="lazy"></iframe>
  `;
  document.body.appendChild(spotlight);
  const spotlightFrame = spotlight.querySelector("iframe");
  const spotlightTitle = spotlight.querySelector("[data-preview-title]");
  const spotlightClose = spotlight.querySelector("[data-preview-close]");
  let active = 0;
  let startX = 0;
  let currentX = 0;
  let dragging = false;
  let pointerId = null;
  let moved = false;

  function showSlide(index) {
    active = (index + slides.length) % slides.length;
    slides.forEach((slide, slideIndex) => {
      const rawOffset = slideIndex - active;
      const wrappedOffset =
        rawOffset > slides.length / 2
          ? rawOffset - slides.length
          : rawOffset < -slides.length / 2
            ? rawOffset + slides.length
            : rawOffset;

      slide.classList.toggle("is-active", slideIndex === active);
      slide.classList.toggle("is-prev", wrappedOffset === -1);
      slide.classList.toggle("is-next", wrappedOffset === 1);
      slide.classList.toggle("is-hidden-left", wrappedOffset < -1);
      slide.classList.toggle("is-hidden-right", wrappedOffset > 1);
      slide.setAttribute("aria-hidden", slideIndex === active ? "false" : "true");
      slide.inert = slideIndex !== active;
    });
    dots.forEach((dot, dotIndex) => {
      dot.classList.toggle("is-active", dotIndex === active);
    });
  }

  function setDrag(value) {
    carousel.style.setProperty("--drag-x", `${value}px`);
  }

  function endDrag() {
    if (!dragging) return;
    dragging = false;
    viewport?.classList.remove("is-dragging");

    const distance = currentX - startX;
    const threshold = Math.max(64, (viewport?.clientWidth || 640) * 0.14);
    setDrag(0);
    moved = Math.abs(distance) > 8;

    if (Math.abs(distance) > threshold) {
      showSlide(active + (distance < 0 ? 1 : -1));
    } else {
      showSlide(active);
    }
  }

  function showPreview(slide) {
    if (!slide.classList.contains("is-active")) return;
    const frame = slide.querySelector(".mockup iframe");
    const title = slide.querySelector("h3")?.textContent || "Project preview";
    if (!frame?.src) return;
    if (spotlightFrame.src !== frame.src) spotlightFrame.src = frame.src;
    spotlightFrame.title = `${title} expanded preview`;
    spotlightTitle.textContent = title;
    spotlight.classList.add("is-visible");
    document.body.classList.add("preview-open");
  }

  function hidePreview() {
    spotlight.classList.remove("is-visible");
    document.body.classList.remove("preview-open");
  }

  prev?.addEventListener("click", () => showSlide(active - 1));
  next?.addEventListener("click", () => showSlide(active + 1));
  dots.forEach((dot, index) => {
    dot.addEventListener("click", () => showSlide(index));
  });

  viewport?.addEventListener("pointerdown", (event) => {
    if (event.target.closest("a, button, input, select, textarea")) return;
    if (event.button !== undefined && event.button !== 0) return;
    dragging = true;
    moved = false;
    pointerId = event.pointerId;
    startX = event.clientX;
    currentX = event.clientX;
    viewport.classList.add("is-dragging");
    viewport.setPointerCapture?.(event.pointerId);
  });

  viewport?.addEventListener("pointermove", (event) => {
    if (!dragging || event.pointerId !== pointerId) return;
    currentX = event.clientX;
    const distance = currentX - startX;
    moved = Math.abs(distance) > 8;
    const constrained = Math.max(-220, Math.min(220, distance));
    setDrag(constrained);
  });

  viewport?.addEventListener("pointerup", endDrag);
  viewport?.addEventListener("pointercancel", endDrag);
  viewport?.addEventListener("lostpointercapture", endDrag);

  viewport?.addEventListener("keydown", (event) => {
    if (event.key === "ArrowLeft") showSlide(active - 1);
    if (event.key === "ArrowRight") showSlide(active + 1);
  });

  viewport?.addEventListener(
    "click",
    (event) => {
      if (moved && !event.target.closest("a, button")) {
        event.preventDefault();
      }
      moved = false;
    },
    true
  );

  slides.forEach((slide) => {
    const previewButton = slide.querySelector("[data-preview]");
    previewButton?.addEventListener("click", () => showPreview(slide));
  });

  spotlightClose?.addEventListener("click", hidePreview);
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") hidePreview();
  });

  showSlide(0);
});
